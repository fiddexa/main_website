let currentLanguage = "en";

function getLanguage(){
  return currentLanguage;
}

function t(key){
  return translations[currentLanguage]?.[key] ?? translations.en[key] ?? key;
}

function setText(selector, key){
  const el = document.querySelector(selector);
  if(el) el.textContent = t(key);
}

function setHTML(selector, key){
  const el = document.querySelector(selector);
  if(el) el.innerHTML = t(key);
}

function setAttr(selector, attribute, key){
  const el = document.querySelector(selector);
  if(el) el.setAttribute(attribute, t(key));
}

function setActivePage(){
  const file = window.location.pathname.split("/").pop() || "index.html";

  let page = "home";

  if(file === "about.html") page = "about";
  if(file === "offers.html") page = "areas";
  if(file === "partner.html") page = "partner";

  document.querySelectorAll("[data-page]").forEach(link => {
    link.classList.toggle("active", link.dataset.page === page);
  });
}

function renderAreas(){
  const list = areas[currentLanguage] || areas.en;

  document.querySelectorAll(".area-list").forEach(container => {
    const href = window.location.pathname.endsWith("offers.html")
      ? "partner.html"
      : "offers.html";

    container.innerHTML = list.map((name, index) => `
      <a href="${href}">
        <span>0${index + 1}</span>
        <strong>${name}</strong>
        <i>→</i>
      </a>
    `).join("");
  });

  document.querySelectorAll(".simple-list").forEach(container => {
    const links = container.querySelectorAll(".simple-list-item");

    links.forEach((link, index) => {
      const title = link.querySelector(".simple-list-title");
      if(title && list[index]) title.textContent = list[index];
    });
  });
}


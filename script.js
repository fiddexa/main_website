function updateDocumentMeta(){
  const file = window.location.pathname.split("/").pop() || "index.html";

  let titleKey = "titleHome";

  if(file === "about.html") titleKey = "titleAbout";
  if(file === "offers.html") titleKey = "titleOffers";
  if(file === "partner.html") titleKey = "titlePartner";

  document.title = t(titleKey);
  document.documentElement.lang = currentLanguage;
}

function applyLanguage(lang){
  if(!translations[lang]) lang = "en";

  currentLanguage = lang;

  localStorage.setItem("fiddexa-lang", lang);

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-lang-label]").forEach(el=>{
    el.textContent = lang.toUpperCase();
  });

  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.dataset.i18n;

    if(translations[lang]?.[key] !== undefined){
      el.textContent = translations[lang][key];
    }
  });

  renderAreas();
  translateHome();
  translateAbout();
  translateOffers();
  translatePartner();
  updateFooter();
  updateDocumentMeta();
  setActivePage();

  document.querySelector(".lang-menu")?.classList.remove("show");
  document.querySelector(".nav")?.classList.remove("open");
}

function setupNavigation(){
  const langButton = document.querySelector(".lang-btn");

  langButton?.addEventListener("click", event=>{
    event.stopPropagation();
    document.querySelector(".lang-menu")?.classList.toggle("show");
  });

  document.querySelectorAll("[data-lang]").forEach(button=>{
    button.addEventListener("click", ()=>{
      applyLanguage(button.dataset.lang);
    });
  });

  const menuButton = document.querySelector(".menu-btn");

  menuButton?.addEventListener("click", ()=>{
    document.querySelector(".nav")?.classList.toggle("open");
  });

  document.querySelectorAll(".main-nav a").forEach(link=>{
    link.addEventListener("click", ()=>{
      document.querySelector(".nav")?.classList.remove("open");
    });
  });

  document.addEventListener("click", event=>{
    if(!event.target.closest(".lang")){
      document.querySelector(".lang-menu")?.classList.remove("show");
    }
  });
}

function setupPartnerForm(){
  const form = document.getElementById("partner-form");

  if(!form) return;

  const status = document.getElementById("form-status");
  const button = form.querySelector(".form-submit");

  form.addEventListener("submit", async event=>{
    event.preventDefault();

    if(button) {
      button.disabled = true;
      button.textContent = t("sending");
    }

    if(status){
      status.textContent = "";
      status.className = "form-status";
    }

    try{
      const response = await fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: {
          Accept: "application/json"
        }
      });

      const data = await response.json();

      if(response.ok && data.success){
        if(status){
          status.textContent = t("success");
          status.className = "form-status success";
        }

        form.reset();
        applyLanguage(currentLanguage);
      }else{
        if(status){
          status.textContent = t("error");
          status.className = "form-status error";
        }
      }

    }catch(error){
      if(status){
        status.textContent = t("networkError");
        status.className = "form-status error";
      }
    }finally{
      if(button){
        button.disabled = false;
        button.textContent = t("formSend");
      }
    }
  });
}

document.addEventListener("DOMContentLoaded", ()=>{
  const saved = localStorage.getItem("fiddexa-lang") || "en";

  setupNavigation();
  setupPartnerForm();
  applyLanguage(saved);
});
